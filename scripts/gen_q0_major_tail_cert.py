#!/usr/bin/env python3
from __future__ import annotations

"""
Generate the ℚ-only certificate artifact for the ε₂ large-β tail budgeting.

This writes:
  Goldbach/Cert/MajorArcModules/Q0MajorTailCertData.lean

The artifact is intentionally tiny and stable: it contains only rational constants and proves
validity by `native_decide`.
"""

from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class Params:
    # Inner bound `M` on ‖innerMajorQ0‖ over β ∈ [-1/2,1/2].
    M: int = 50_000
    # Tail budget εl.
    epsl_num: int = 2
    epsl_den: int = 1


def render(p: Params) -> str:
    return f"""import Goldbach.Cert.MajorArcModules.Q0MajorTailCert

/-!
Generated certificate artifact (Q0 route, ε₂ large-β tail): rational budgeting constants.

This file is generated by `scripts/gen_q0_major_tail_cert.py`.
-/

namespace Goldbach.Cert.MajorArcModules.Q0MajorTailCertData

open Goldbach.Cert.MajorArcModules.Q0MajorTailCert

noncomputable section

def data : Data :=
  {{ M := ({p.M} : ℚ)
    εl := ({p.epsl_num} : ℚ) / ({p.epsl_den} : ℚ) }}

theorem data_valid : data.Valid := by
  native_decide

end

end Goldbach.Cert.MajorArcModules.Q0MajorTailCertData
"""


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    out_path = root / "Goldbach" / "Cert" / "MajorArcModules" / "Q0MajorTailCertData.lean"
    out_path.write_text(render(Params()), encoding="utf-8")
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()

