#!/usr/bin/env python3
"""
Generate the Q0-route major-arc certificate artifact (numbers only).

This keeps the generated data purely in ℚ (Lean `Rat` literals), so the checker can use
`native_decide` deterministically.

For now, this script emits a minimal placeholder certificate; update EPS1/EPS2 once concrete
budgets are computed.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class Budgets:
    eps1_q: str
    eps2_q: str


EPS = Budgets(eps1_q="(4 : ℚ)", eps2_q="(4 : ℚ)")


def render(b: Budgets) -> str:
    return "\n".join(
        [
            "import Goldbach.Cert.MajorArcModules.Q0Certificate",
            "",
            "/-!",
            "Generated certificate artifact (Q0 route): error budgets `ε₁, ε₂` in `ℚ`.",
            "",
            "This file is generated by `scripts/gen_major_arc_q0_cert.py`.",
            "-/",
            "",
            "namespace Goldbach.Cert.MajorArcModules.Q0CertData",
            "",
            "open Goldbach.Cert.MajorArcModules.Q0Certificate",
            "",
            "noncomputable section",
            "",
            "def cert : Q0Cert :=",
            f"  {{ ε₁ := {b.eps1_q}",
            f"    ε₂ := {b.eps2_q} }}",
            "",
            "theorem cert_valid : cert.cert.Valid := by",
            "  native_decide",
            "",
            "end",
            "",
            "end Goldbach.Cert.MajorArcModules.Q0CertData",
            "",
        ]
    )


def main() -> None:
    repo_root = Path(__file__).resolve().parents[1]
    out = repo_root / "Goldbach" / "Cert" / "MajorArcModules" / "Q0CertData.lean"
    out.write_text(render(EPS), encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()

