#!/usr/bin/env python3
"""
Generate the ε₁ Type-I / constant-mode certificate artifact.

This writes:
  Goldbach/Cert/MajorArcModules/Q0MinorTypeICertData.lean

The artifact is purely rational: it records an advertised constant `A3` and a generated
upper bound `U`, with Lean checking `0 ≤ U ≤ A3` by computation.

If `--u` is omitted, the script evaluates the current exact zero-mode window expression at the
chosen `X` and emits a padded rational candidate. That evaluation is useful for calibration, but
it is not yet a fully rigorous proof backend.
"""

from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction
from pathlib import Path
import argparse

from q0_minor_cert_common import X0, candidate_typei_u


def parse_rat(text: str) -> Fraction:
    try:
        return Fraction(text)
    except Exception as exc:  # pragma: no cover - defensive CLI parsing
        raise argparse.ArgumentTypeError(f"bad rational: {text}") from exc


def lean_q(fr: Fraction) -> str:
    if fr.denominator == 1:
      return f"({fr.numerator} : ℚ)"
    return f"(({fr.numerator} : ℚ) / ({fr.denominator} : ℚ))"


@dataclass(frozen=True)
class Payload:
    a3: Fraction
    u: Fraction


def render(p: Payload) -> str:
    return "\n".join(
        [
            "import Goldbach.Cert.MajorArcModules.Q0MinorTypeICert",
            "",
            "/-!",
            "Generated certificate artifact for the ε₁ Type-I / constant-mode route.",
            "",
            "This file is generated by `scripts/gen_q0_minor_typeI_cert.py`.",
            "-/",
            "",
            "namespace Goldbach.Cert.MajorArcModules.Q0MinorTypeICertData",
            "",
            "open Goldbach.Cert.MajorArcModules.Q0MinorTypeICert",
            "",
            "noncomputable section",
            "",
            "def data : Data :=",
            f"  {{ A3 := {lean_q(p.a3)}",
            f"    U := {lean_q(p.u)} }}",
            "",
            "theorem data_valid : data.Valid := by",
            "  native_decide",
            "",
            "end",
            "",
            "end Goldbach.Cert.MajorArcModules.Q0MinorTypeICertData",
            "",
        ]
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--a3", type=parse_rat, default=Fraction(0), help="advertised rational A3")
    parser.add_argument(
        "--u",
        type=parse_rat,
        default=None,
        help="generated rational upper bound U (defaults to A3)",
    )
    parser.add_argument(
        "--x",
        type=int,
        default=X0,
        help="evaluation point X for the current zero-mode candidate (default: X0)",
    )
    parser.add_argument(
        "--pad-bps",
        type=int,
        default=100,
        help="inflate the floating candidate by this many basis points before rationalizing",
    )
    args = parser.parse_args()

    if args.u is None:
        raw_u = candidate_typei_u(args.x)
        scaled = raw_u * (1.0 + args.pad_bps / 10_000.0)
        u = Fraction(str(scaled))
        print(f"computed provisional Type-I candidate at X={args.x}: U≈{raw_u:.12g}, padded≈{scaled:.12g}")
    else:
        u = args.u
    a3 = u if args.a3 == 0 else args.a3
    payload = Payload(a3=a3, u=u)

    repo_root = Path(__file__).resolve().parents[1]
    out = repo_root / "Goldbach" / "Cert" / "MajorArcModules" / "Q0MinorTypeICertData.lean"
    out.write_text(render(payload), encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
