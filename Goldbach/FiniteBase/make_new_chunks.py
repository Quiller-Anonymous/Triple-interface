#!/usr/bin/env python3
"""
make_proof_chunks.py  —  robust generator for finite-base chunks

Modes
-----
  axiomatic   : coverage axiom only (fastest)
  sumonly     : proves p+q=n for each row; assumes primality & completeness
  soundness   : proves Prime p, Prime q, and p+q=n; assumes completeness

Scaling
-------
  --subsplit K  splits each chunk_XXX.json into K Lean modules with smaller N-windows.
                This drastically reduces per-module kernel work.

Typical uses
------------
  # light + safe: most chunks axiomatic, a few soundness
  python tools/make_proof_chunks.py --in goldbach_chunks --out Goldbach/FiniteBase --emit-kit --mode axiomatic

  # medium: prove sums, assume primes (fast), split into 5 subchunks per window
  python tools/make_proof_chunks.py --in goldbach_chunks --out Goldbach/FiniteBase --emit-kit --mode sumonly --subsplit 5

  # heavy: full soundness, but sub-split to keep modules small
  python tools/make_proof_chunks.py --in goldbach_chunks --out Goldbach/FiniteBase --emit-kit --mode soundness --subsplit 5
"""
import argparse, hashlib, json, re, sys, math
from pathlib import Path
from typing import List, Tuple

def alphabetic_suffix(n: int) -> str:
    """Convert 0-based index to a lowercase alphabetic suffix: 0→a, …, 25→z, 26→aa, etc."""
    if n < 0:
        raise ValueError("suffix index must be non-negative")
    chars = []
    k = n
    while True:
        k, r = divmod(k, 26)
        chars.append(chr(ord('a') + r))
        if k == 0:
            break
        k -= 1  # excel-style carry
    return ''.join(reversed(chars))

KIT = r'''/-
Minimal kit so chunks typecheck standalone. If your project already provides these,
delete this file and switch the generated imports to your module.
-/
import Mathlib.Data.Nat.Prime
import Mathlib.Data.Nat.Parity

namespace Goldbach.Base

/-- A Goldbach representation of an even natural `n`. -/
structure GoldbachRep (n : Nat) : Prop where
  p q  : Nat
  hp   : Nat.Prime p
  hq   : Nat.Prime q
  hsum : p + q = n

/-- Finite base restricted to `[a,b]`. -/
def FiniteBaseOn (a b : Nat) : Prop :=
  ∀ n, Even n → a ≤ n → n ≤ b → GoldbachRep n

/-- Glue `[a,b]` and `[b+1,c]`. -/
lemma FiniteBaseOn.union_adjacent {a b c : Nat}
  (h₁ : FiniteBaseOn a b) (h₂ : FiniteBaseOn (b+1) c) :
  FiniteBaseOn a c := by
  intro n hn hna hnc
  by_cases hnb : n ≤ b
  · exact h₁ n hn hna hnb
  ·
    have hb1 : b+1 ≤ n := by
      have : ¬ n < b+1 := by
        intro hlt; exact hnb (Nat.le_of_lt_succ hlt)
      exact le_of_not_gt this
    exact h₂ n hn hb1 hnc

end Goldbach.Base
'''

AXIOM_TMPL = '''/-- AUTOGENERATED: Chunk [{lo}..{hi}] (even n only).
    Source: {fname}  •  SHA256(JSON): {sha} -/
import «FiniteBaseChunkKit»
open Goldbach.Base

namespace {ns}.Chunks.{mod}

def nLo : Nat := {lo}
def nHi : Nat := {hi}
def dataSHA256 : String := "{sha}"

/-- Finite-conditional stub: every even n in [nLo,nHi] has a representation. -/
axiom coverage : FiniteBaseOn nLo nHi
theorem base : FiniteBaseOn nLo nHi := coverage

end {ns}.Chunks.{mod}
'''

SUMONLY_TMPL = '''/-- AUTOGENERATED (sum-only mode): Chunk [{lo}..{hi}]
    Source: {fname}  •  SHA256(JSON): {sha} -/
import «FiniteBaseChunkKit»
open Goldbach.Base

namespace {ns}.Chunks.{mod}

def nLo : Nat := {lo}
def nHi : Nat := {hi}
def dataSHA256 : String := "{sha}"

-- Table of (n,p,q) witnesses for this sub-window (only used to prove sums).
def table : Array (Nat × Nat × Nat) :=
  #[
{rows}
  ]

/-- For any row i of `table`, the sum matches: p+q = n. -/
lemma entry_sum (i : Fin table.size) :
  let e := table[i]
  (e.snd.fst + e.snd.snd = e.fst) := by
  intro e
  rcases e with ⟨n, pq⟩
  rcases pq with ⟨p, q⟩
  simp  -- reduces to `rfl` on numerals

/-- Assumed primality for this sub-window (kept as a single axiom). -/
axiom primes_ok :
  ∀ i : Fin table.size,
    let e := table[i]; Nat.Prime e.snd.fst ∧ Nat.Prime e.snd.snd

/-- Assumed completeness for this sub-window. -/
axiom completeness :
  ∀ n, Even n → nLo ≤ n → n ≤ nHi → ∃ i : Fin table.size, (table[i].fst) = n

/-- Finite base for this sub-window, from (proved) sums + (assumed) primes & completeness. -/
theorem base : FiniteBaseOn nLo nHi := by
  intro n hn hna hnb
  rcases completeness n hn hna hnb with ⟨i, hmatch⟩
  have hs := entry_sum i
  have ⟨hp, hq⟩ := primes_ok i
  rcases table[i] with ⟨n', pq⟩
  rcases pq with ⟨p,q⟩
  -- rewrite n' to n using completeness
  simp [GoldbachRep, hmatch] at hs
  exact ⟨p, q, hp, hq, by simpa [hmatch] using hs⟩

end {ns}.Chunks.{mod}
'''

SOUND_TMPL = '''/-
AUTOGENERATED (soundness mode): Chunk [{lo}..{hi}]
    Source: {fname}  •  SHA256(JSON): {sha}
-/
import Goldbach.FiniteBase.FiniteBaseChunkKit
open Goldbach.Base

set_option maxRecDepth 8000
set_option diagnostics true

namespace {ns}.Chunks.{mod}

noncomputable section

def nLo : Nat := {lo}
def nHi : Nat := {hi}
def dataSHA256 : String := "{sha}"

-- Table of (n,p,q) witnesses for this sub-window.
def table : Array (Nat × Nat × Nat) :=
  #[
{rows}
  ]

/-- For any row i of `table`, both entries are prime and sum to its n. -/
lemma entry_sound (i : Fin table.size) :
    ∃ p q,
      table[i].snd.fst = p ∧ table[i].snd.snd = q ∧ Nat.Prime p ∧ Nat.Prime q ∧ p + q = table[i].fst := by
  classical
  -- Enumerate the finitely many rows and discharge each by computation.
  fin_cases i <;>
    refine ⟨_, _, rfl, rfl, ?_, ?_, ?_⟩ <;>
    native_decide

/-- Finite base for this sub-window, assuming completeness of the table coverage. -/
theorem base
  (completeness :
    ∀ n, Even n → nLo ≤ n → n ≤ nHi →
      ∃ i : Fin table.size, (table[i].fst) = n) :
  FiniteBaseOn nLo nHi := by
  intro n hn hna hnb
  rcases completeness n hn hna hnb with ⟨i, hmatch⟩
  have h := entry_sound i
  rcases h with ⟨p, q, rflp, rflq, hp, hq, hsum⟩
  have hmatch' : table[↑i].1 = n := by simpa using hmatch
  have hsum' : p + q = n := hsum.trans hmatch'
  simpa [GoldbachRep, hmatch] using ⟨p, ⟨hp, ⟨q, ⟨hq, hsum'⟩⟩⟩⟩

end

end {ns}.Chunks.{mod}
'''

FNAME_RE = re.compile(r'^chunk_(\d{3})\.json$')

def sha256_file(path: Path) -> str:
    import hashlib
    h = hashlib.sha256()
    with path.open('rb') as f:
        for block in iter(lambda: f.read(1<<20), b''):
            h.update(block)
    return h.hexdigest()

def bounds(idx: int, width: int, start_even: int) -> Tuple[int,int]:
    lo = idx*width + 1
    hi = (idx+1)*width
    if lo < start_even: lo = start_even
    return lo, hi

def split_rows_by_n(rows: List[dict], parts: int) -> List[List[Tuple[int,int,int]]]:
    """Split by N into `parts` sublists with contiguous n-ranges."""
    if parts <= 1:  # no split
        return [[(r["n"], r["p"], r["q"]) for r in rows]]
    # rows are sorted by n already
    nmin = rows[0]["n"]; nmax = rows[-1]["n"]
    span = nmax - nmin + 2  # even step
    slice_span = span // parts
    out: List[List[Tuple[int,int,int]]] = [[] for _ in range(parts)]
    for (n,p,q) in ((r["n"], r["p"], r["q"]) for r in rows):
        k = min(parts-1, (n - nmin) // slice_span)
        out[k].append((n,p,q))
    # ensure no empty (can happen at edges)
    out = [chunk for chunk in out if chunk]
    return out

def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--in', dest='inp', required=True)
    ap.add_argument('--out', dest='out', required=True)
    ap.add_argument('--emit-kit', action='store_true')
    ap.add_argument('--namespace', default='Goldbach.FiniteBase')
    ap.add_argument('--width', type=int, default=10_000)
    ap.add_argument('--start-even', type=int, default=4)
    ap.add_argument('--mode', choices=['axiomatic','sumonly','soundness'], default='axiomatic')
    ap.add_argument('--subsplit', type=int, default=1, help='split each JSON chunk into this many subchunks')
    ap.add_argument('--max-rows', type=int, default=1500, help='maximum table rows per generated Lean chunk')
    args = ap.parse_args(argv)

    in_dir  = Path(args.inp).resolve()
    out_dir = Path(args.out).resolve()
    chunks_dir = out_dir / 'Chunks'
    chunks_dir.mkdir(parents=True, exist_ok=True)

    if args.emit_kit:
        (out_dir / 'FiniteBaseChunkKit.lean').write_text(KIT, encoding='utf-8')

    files = sorted((p for p in in_dir.iterdir() if p.is_file() and FNAME_RE.match(p.name)), key=lambda p: p.name)
    if not files:
        print(f'No chunk_XXX.json files in {in_dir}', file=sys.stderr)
        return 2

    for f in files:
        idx = int(FNAME_RE.match(f.name).group(1))
        lo, hi = bounds(idx, args.width, args.start_even)
        sha = sha256_file(f)
        data = json.loads(f.read_text(encoding='utf-8'))
        target_parts = math.ceil(len(data) / args.max_rows) if args.max_rows > 0 else 1
        parts = split_rows_by_n(data, max(1, args.subsplit, target_parts))
        for j, triples in enumerate(parts):
            # compute sub-window bounds from triples
            sub_lo = triples[0][0]; sub_hi = triples[-1][0]
            rows_str = ",\n".join(f"    ({n}, ({p}, {q}))" for (n,p,q) in triples)
            suffix = alphabetic_suffix(j)
            mod = f"Chunk{idx:03d}_{suffix}_{'axiom' if args.mode=='axiomatic' else ('sum' if args.mode=='sumonly' else 'verified')}"
            if args.mode == 'axiomatic':
                code = AXIOM_TMPL.format(lo=sub_lo, hi=sub_hi, fname=f.name, sha=sha, ns=args.namespace, mod=mod)
            elif args.mode == 'sumonly':
                code = SUMONLY_TMPL.format(lo=sub_lo, hi=sub_hi, fname=f.name, sha=sha, ns=args.namespace, mod=mod, rows=rows_str)
            else:
                code = SOUND_TMPL.format(lo=sub_lo, hi=sub_hi, fname=f.name, sha=sha, ns=args.namespace, mod=mod, rows=rows_str)

            (chunks_dir / f'{mod}.lean').write_text(code, encoding='utf-8')
            print(f'Wrote {chunks_dir / (mod + ".lean")}  [{sub_lo}..{sub_hi}]  {args.mode}')

    print('Done.')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
